    def detailContent(self, ids):
        result = {"list": []}
        try:
            url = ids[0] if isinstance(ids, list) else ids
            url = str(url or '').strip()
            if not self.match_domain(url, self.DOMAINS):
                return result
            pid = parse_qs(urlparse(url).query, keep_blank_values=True).get('pid', [''])[0]
            if not pid:
                return result
            data = self._fetch(pid)
            items = safe_extract(data, ['data', 'videoList'], []) or []
            if not isinstance(items, list) or not items:
                return result
            root_title = self._clean(safe_extract(data, ['data', 'title'], '') or '')
            plays, cover = [], ''
            for idx, item in enumerate(items):
                if not isinstance(item, dict) or not item:
                    continue
                title = self._clean(item.get('title') or root_title or ('EP%d' % (idx + 1)))
                if len(items) > 1 and not re.match(r'^EP\d+', title, re.I):
                    title = 'EP%d-%s' % (idx + 1, title)
                if not cover:
                    cover = item.get('imgPath') or ''
                stream = self._pick_stream(item)
                plays.append('%s$%s|%d|%s|%s' % (title, pid, idx, stream, url))
            if not plays:
                return result
            name = root_title or self._clean(safe_extract(data, ['data', 'title'], '') or '网易视频')
            result['list'] = [self.build_vod(pid, name, cover, '', name, '网易', '#'.join(plays))]
        except Exception:
            pass
        return result
    
