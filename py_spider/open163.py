    def playerContent(self, flag, id, vipFlags):
        try:
            parts = str(id).split('|')
            pid = parts[0] if len(parts) > 0 else ''
            idx = int(parts[1]) if len(parts) > 1 and parts[1].isdigit() else 0
            url = parts[2] if len(parts) > 2 else ''
            page = parts[-1] if len(parts) > 3 else ''
            if not url.startswith('http'):
                url = ''
                try:
                    data = self._fetch(pid)
                    items = safe_extract(data, ['data', 'videoList'], []) or []
                    if isinstance(items, list) and idx < len(items) and isinstance(items[idx], dict):
                        url = self._pick_stream(items[idx])
                except Exception:
                    pass
            if url.startswith('http'):
                header = {'Referer': 'https://open.163.com/', 'User-Agent': self.headers['User-Agent']}
                return {"parse": 0, "url": url, "header": json.dumps(header)}
            if page:
                return {"parse": 1, "url": page, "header": json.dumps({'Referer': page, 'User-Agent': self.headers['User-Agent']})}
            return {"parse": 1, "url": id}
        except Exception:
            return {"parse": 1, "url": id}
    
    def _fetch(self, pid):
        text = self.get(self.API.format(pid=pid), headers=getattr(self, 'api_headers', self.API_HEADERS), timeout=10)
        return json.loads(text)
    
    def _pick_stream(self, item):
        try:
            sized, alls = [], []
            for proto in self.PROTOS:
                for level in self.LEVELS:
                    raw = item.get('%s%sUrlOrign' % (proto, level)) or item.get('%s%sUrl' % (proto, level)) or ''
                    if not raw:
                        continue
                    size = item.get('%s%sSizeOrign' % (proto, level)) or item.get('%s%sSize' % (proto, level)) or 0
                    try:
                        size = int(size)
                    except Exception:
                        size = 0
                    entry = (self.QUALITY_RANK.get(level, 0), size, raw)
                    alls.append(entry)
                    if size != 0:
                        sized.append(entry)
            pool = sized or alls
            pool = [x for x in pool if str(x[2]).startswith('http')]
            if not pool:
                return ''
            pool.sort(key=lambda x: (x[0], x[1]), reverse=True)
            return pool[0][2]
        except Exception:
            return ''
    
    def _clean(self, s):
        s = self.legalize(s or '')
        return s.replace('#', '').replace('$', '').strip()
